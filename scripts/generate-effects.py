def with_python(
    metadata: dict[str, Any],
    overrides: dict[str, Any],
    enum_exports: dict[str, Any] | None = None,
) -> dict[str, Any]:
    ids = {effect["id"] for effect in metadata["effects"]}
    if set(overrides) - ids:
        raise ValueError(
            f"Python overrides reference unknown effects: {sorted(set(overrides) - ids)}"
        )
    effects = []
    for effect in metadata["effects"]:
        python = dict(overrides.get(effect["id"], {}))
        python["name"] = "".join(word.title() for word in effect["id"].split("_"))
        python["module"] = "vestra.effects." + python.get("module", "stylize")
        python.setdefault("base", "Effect")
        python.setdefault("doc", None)
        python["enums"] = {
            **{
                parameter["name"]: python.get("enums", {}).get(
                    parameter["name"],
                    python["name"]
                    + "".join(word.title() for word in parameter["name"].split("_")),
                )
                for parameter in effect["parameters"]
                if parameter["kind"] == "enum"
            },
            **python.get("enums", {}),
        }
        factory = python.pop(
            "helper", "amount" if python["base"] == "_AmountEffect" else "positional"
        )
        python["collection"] = (
            None
            if factory is None
            else {"factory": factory, "parameter_order": python.pop("helper_order", [])}
        )
        effects.append(
            {**effect, "python": python, "units": list(python.pop("units", {}).items())}
        )
    return {**metadata, "effects": effects, "enum_exports": enum_exports or {}}


def arguments(effect: dict[str, Any]) -> ast.arguments:
    python = effect["python"]
    fields = {item["name"]: item for item in effect["parameters"]}
    order = python.get("order", list(fields))
    if len(order) != len(fields) or set(order) != set(fields):
        raise ValueError(
            f"{effect['id']}: constructor order must cover every parameter once"
        )
    count = python.get("positional", len(order))
    if not isinstance(count, int) or not 0 <= count <= len(order):
        raise ValueError(f"{effect['id']}: invalid positional argument count")
    args, defaults = [], []
    for name in order:
        parameter = fields[name]
        kind = parameter["kind"]
        if kind not in KINDS:
            raise ValueError(f"{effect['id']}.{name}: unsupported kind {kind!r}")
        annotation = python.get("annotations", {}).get(name)
        enum = python.get("enums", {}).get(name)
        if annotation is None:
            if kind == "enum" and enum is None:
                raise ValueError(f"{effect['id']}.{name}: missing Python enum class")
            annotation = enum + " | str" if kind == "enum" else ANNOTATIONS[kind]
        value = python.get("defaults", {}).get(name, parameter["default"])
        if kind == "enum" and (
            enum is None
            or not enum.isidentifier()
            or value not in parameter["enum_values"]
        ):
            raise ValueError(f"{effect['id']}.{name}: invalid Python enum/default")
        expression = python.get("expressions", {}).get(name)
        if (
            expression is None
            and kind == "active_interval"
            and not parameter["required"]
        ):
            expression = "ActiveInterval()"
        if expression is not None:
            default = ast.parse(expression, mode="eval").body
        elif value is not None:
            expression = f"{enum}.{value.upper()}" if kind == "enum" else repr(value)
            default = ast.parse(expression, mode="eval").body
        elif not parameter["required"] or name in python.get("defaults", {}):
            default = ast.Constant(None)
        else:
            default = None
        args.append(
            ast.arg(arg=name, annotation=ast.parse(annotation, mode="eval").body)
        )
        defaults.append(default)
    if "positional" not in python:
        first_default = next(
            (i for i, default in enumerate(defaults) if default is not None), len(order)
        )
        if any(default is None for default in defaults[first_default:]):
            count = first_default
    positional_defaults = defaults[:count]
    first = next(
        (i for i, default in enumerate(positional_defaults) if default is not None),
        count,
    )
    if any(default is None for default in positional_defaults[first:]):
        raise ValueError(
            f"{effect['id']}: required positional argument follows a default"
        )
    return ast.arguments(
        posonlyargs=[],
        args=[ast.arg(arg="self"), *args[:count]],
        defaults=positional_defaults[first:],
        vararg=None,
        kwonlyargs=[
            *args[count:],
            ast.arg(arg="id", annotation=ast.parse("str | None", mode="eval").body),
        ],
        kw_defaults=[*defaults[count:], ast.Constant(None)],
        kwarg=None,
    )


def parameters(args: ast.arguments) -> list[tuple[ast.arg, ast.expr | None]]:
    defaults = [None] * (len(args.args) - len(args.defaults)) + args.defaults
    return list(zip(args.args + args.kwonlyargs, defaults + args.kw_defaults))


def validate(metadata: dict[str, Any]) -> None:
    ids: set[str] = set()
    names: set[str] = set()
    enums: dict[str, list[str]] = {}
    for effect in metadata["effects"]:
        identifier = effect["id"]
        python = effect["python"]
        if not isinstance(python, dict):
            raise ValueError(f"{identifier}: missing Python authoring metadata")
        if identifier in ids or python["name"] in names:
            raise ValueError(f"{identifier}: duplicate effect id or Python name")
        ids.add(identifier)
        names.add(python["name"])
        if (
            not python["module"].startswith("vestra.effects.")
            or not python["module"].removeprefix("vestra.effects.").isidentifier()
            or not python["name"].isidentifier()
        ):
            raise ValueError(f"{identifier}: invalid Python module or class name")
        if python.get("advanced_serialization", "registered") not in {
            "registered",
            "direct",
        }:
            raise ValueError(f"{identifier}: invalid advanced serialization policy")
        expected = [item["name"] for item in effect["parameters"]]
        if len(expected) != len(set(expected)):
            raise ValueError(f"{identifier}: duplicate parameter name")
        for key in ("enums", "annotations", "defaults", "expressions"):
            if set(python.get(key, {})) - set(expected):
                raise ValueError(f"{identifier}: {key} reference an unknown parameter")
        if set(python.get("defaults", {})) & set(python.get("expressions", {})):
            raise ValueError(f"{identifier}: duplicate default override")
        args = arguments(effect)
        authored = parameters(args)
        actual = [arg.arg for arg, _ in authored if arg.arg not in {"self", "id"}]
        if any(arg.annotation is None for arg, _ in authored if arg.arg != "self"):
            raise ValueError(
                f"{identifier}: every public argument needs a type annotation"
            )
        for item in effect["parameters"]:
            if item["kind"] not in KINDS:
                raise ValueError(
                    f"{identifier}.{item['name']}: unsupported kind {item['kind']!r}"
                )
            for prefix in ("", "integer_"):
                minimum, maximum = (
                    item.get(prefix + "minimum"),
                    item.get(prefix + "maximum"),
                )
                if minimum is not None and maximum is not None and minimum > maximum:
                    raise ValueError(f"{identifier}.{item['name']}: inverted bounds")
            if item["kind"] == "enum" and (
                not item["enum_values"] or item["default"] not in item["enum_values"]
            ):
                raise ValueError(f"{identifier}.{item['name']}: invalid enum/default")
            if item["kind"] == "enum":
                name = python["enums"][item["name"]]
                members = [value.upper() for value in item["enum_values"]]
                if len(members) != len(set(members)):
                    raise ValueError(f"Python enum {name} contains duplicate members")
                if any(not member.isidentifier() for member in members):
                    raise ValueError(
                        f"Python enum {name} contains an invalid member name"
                    )
                if name in enums and enums[name] != item["enum_values"]:
                    raise ValueError(
                        f"Python enum {name} has inconsistent ordered values"
                    )
                enums[name] = item["enum_values"]
        if set(dict(effect["units"])) - set(expected):
            raise ValueError(f"{identifier}: units reference an unknown parameter")
        collection = python["collection"]
        if collection is not None:
            if collection["factory"] not in {
                "positional",
                "amount",
                "palette",
                "stylized",
            }:
                raise ValueError(f"{identifier}: unsupported collection factory")
            order = collection["parameter_order"] or actual
            if len(order) != len(actual) or set(order) != set(actual):
                raise ValueError(
                    f"{identifier}: helper order must cover every parameter once"
                )
    for effect in metadata["effects"]:
        base = effect["python"]["base"]
        if base not in names | {"Effect", "_AmountEffect"}:
            raise ValueError(f"{effect['id']}: unsupported base {base!r}")
    if set(metadata.get("enum_exports", {})) - set(enums):
        raise ValueError("Python enum export layout references an unknown enum")
    if not isinstance(metadata["schema"], str) or not metadata["schema"].endswith("\n"):
        raise ValueError("core export must include the canonical schema text")
    schema = json.loads(metadata["schema"])
    branches = {
        item["$ref"].removeprefix("#/$defs/").removesuffix("_effect")
        for item in schema["$defs"]["effect"]["oneOf"]
    }
    if branches != ids:
        raise ValueError("schema effect branches do not match the catalog")


def function_header(
    name: str, args: ast.arguments, returns: str, indent: str = "    "
) -> str:
    lines = [f"{indent}def {name}("]
    positional = len(args.args)
    for index, (arg, default) in enumerate(parameters(args)):
        if index == positional and args.kwonlyargs:
            lines.append(f"{indent}    *,")
        annotation = f": {ast.unparse(arg.annotation)}" if arg.annotation else ""
        value = f" = {ast.unparse(default)}" if default is not None else ""
        lines.append(f"{indent}    {arg.arg}{annotation}{value},")
    lines.append(f"{indent}) -> {returns}:")
    return "\n".join(lines)


def property_types(parameter: dict[str, Any], annotation: str) -> tuple[str, str]:
    kind = parameter["kind"]
    getter = {
        "scalar_property": "BindableScalarProperty",
        "plain_track": "ScalarProperty",
        "colour": "str",
        "palette": "tuple[str, ...]",
        "palette_stops": "tuple[float, ...] | None",
        "period": "float | None",
        "integer": "int",
        "number": "float",
        "point2d": "Point",
        "point_property": "BindablePointProperty",
        "boolean": "bool",
        "active_interval": "ActiveInterval",
        "string": "str",
        "font": annotation,
        "enum": annotation.removesuffix(" | str"),
    }[kind]
    setter = getter + " | str" if kind == "enum" else annotation
    return getter, setter


def render_class(
    effect: dict[str, Any], effects: list[dict[str, Any]], *, amount_base: bool = False
) -> str:
    python = effect["python"]
    name = "_AmountEffect" if amount_base else python["name"]
    base = "Effect" if amount_base else python["base"]
    lines = [f"class {name}({base}):"]
    if python["doc"] and not amount_base:
        doc = python["doc"].replace('"""', '\\"\\"\\"')
        lines.append(textwrap.indent('"""' + doc + '"""', "    "))
    if base == "_AmountEffect":
        lines.append(f"    effect_type = {effect['id']!r}")
        return "\n".join(lines) + "\n"
    lines.append("    __slots__ = ()")
    if not amount_base:
        lines.append(f"    effect_type = {effect['id']!r}")
    args = arguments(effect)
    fields = {
        arg.arg: ast.unparse(arg.annotation)
        for arg, _ in parameters(args)
        if arg.arg not in {"self", "id"}
    }
    lines += ["", function_header("__init__", args, "None")]
    lines.append(
        "        Effect.__init__(self)"
        if base != "Effect"
        else "        super().__init__()"
    )
    lines += ["        self._init(", "            {"]
    lines.extend(f"                {field!r}: {field}," for field in fields)
    lines += ["            },", "            id=id,", "        )"]
    inherited = next((item for item in effects if item["python"]["name"] == base), None)
    inherited_names = (
        {item["name"] for item in inherited["parameters"]} if inherited else set()
    )
    for parameter in effect["parameters"]:
        field = parameter["name"]
        if field in inherited_names:
            continue
        getter, setter = property_types(parameter, fields[field])
        kind = parameter["kind"]
        storage = (
            "_properties"
            if kind in {"scalar_property", "plain_track", "point_property"}
            else "_values"
        )
        access = (
            f"self.{storage}.get({field!r})"
            if kind in {"font", "period", "palette_stops"}
            or (storage == "_values" and python.get("get_values", False))
            else f"self.{storage}[{field!r}]"
        )
        method = (
            "_set_property"
            if kind in {"scalar_property", "plain_track"}
            else "_set_value"
        )
        lines += [
            "",
            "    @property",
            f"    def {field}(self) -> {getter}:",
            f"        return cast({getter}, {access})",
            "",
            f"    @{field}.setter",
            f"    def {field}(self, value: {setter}) -> None:",
            f"        self.{method}({field!r}, value)",
        ]
    return "\n".join(lines) + "\n"


def helper_arguments(effect: dict[str, Any]) -> ast.arguments:
    collection = effect["python"]["collection"]
    authored = parameters(arguments(effect))
    values = {arg.arg: (arg, default) for arg, default in authored if arg.arg != "self"}
    order = collection["parameter_order"] or [name for name in values if name != "id"]
    kinds = {item["name"]: item["kind"] for item in effect["parameters"]}
    kwargs, defaults = [], []
    for name in [*order, "id"]:
        arg, default = values[name]
        annotation = ast.unparse(arg.annotation)
        annotation = (
            annotation.replace("ScalarProperty", "ScalarTrack")
            if collection["factory"] in {"palette", "stylized"}
            else annotation.replace(" | ScalarProperty", "")
        )
        if kinds.get(name) in {"point2d", "point_property"}:
            annotation = "Point"
        elif kinds.get(name) == "font":
            annotation = "FontAsset | None"
        if default is not None and ast.unparse(default) == "CHARACTER_SETS['standard']":
            default = ast.Constant(" .:-=+*#%@")
        kwargs.append(
            ast.arg(arg=name, annotation=ast.parse(annotation, mode="eval").body)
        )
        defaults.append(default)
    return ast.arguments(
        posonlyargs=[],
        args=[ast.arg(arg="self")],
        vararg=None,
        kwonlyargs=kwargs,
        kw_defaults=defaults,
        kwarg=None,
        defaults=[],
    )


def render_helper(effect: dict[str, Any]) -> str:
    args = helper_arguments(effect)
    name = effect["python"]["name"] + "Effect"
    factory = effect["python"]["collection"]["factory"]
    fields = [arg.arg for arg in args.kwonlyargs if arg.arg != "id"]
    if factory in {"palette", "stylized"}:
        method = "_create_palette" if factory == "palette" else "_create_stylized"
        values = [
            "            {",
            *[f"                {field!r}: {field}," for field in fields],
            "            },",
        ]
    else:
        method = "_create"
        values = [
            f"            {value},"
            for value in ([repr(effect["id"])] if factory == "amount" else []) + fields
        ]
    return (
        function_header("add_" + effect["id"], args, name) + "\n"
        f"        return self._append(\n            {name}.{method},\n            id,\n"
        + "\n".join(values)
        + "\n        )\n"
    )


def enum_definitions(effects: list[dict[str, Any]]) -> dict[str, list[str]]:
    return {
        effect["python"]["enums"][parameter["name"]]: parameter["enum_values"]
        for effect in effects
        for parameter in effect["parameters"]
        if parameter["kind"] == "enum"
    }


def render_enums(effects: list[dict[str, Any]]) -> str:
    return "\n\n\n".join(
        f"class {name}(Enum):\n"
        + "\n".join(f"    {value.upper()} = {value!r}" for value in values)
        for name, values in enum_definitions(effects).items()
    )


def advanced_base(effect: dict[str, Any]) -> str:
    python = effect["python"]
    if "advanced_base" in python:
        return python["advanced_base"]
    if python["base"] == "_AmountEffect":
        return "_AmountEffect"
    if python["base"] != "Effect":
        return python["base"] + "Effect"
    if python["collection"]["factory"] in {"palette", "stylized"} or any(
        parameter["kind"]
        in {"palette", "palette_stops", "period", "font", "point_property"}
        for parameter in effect["parameters"]
    ):
        return "GenericEffect"
    return "Effect"


def advanced_types(
    parameter: dict[str, Any], python: dict[str, Any]
) -> tuple[str, str]:
    kind = parameter["kind"]
    if kind == "scalar_property":
        return "ModulatableScalarTrack", "int | float"
    if kind == "plain_track":
        return "ScalarTrack", "int | float"
    if kind == "point_property":
        return "PointTrack", "Point"
    if kind == "font":
        return "str | None", "FontAsset | None"
    annotation = python.get("annotations", {}).get(parameter["name"])
    if annotation is None:
        annotation = (
            python["enums"][parameter["name"]] + " | str"
            if kind == "enum"
            else ANNOTATIONS[kind]
        )
    getter, setter = property_types(parameter, annotation)
    if kind == "enum":
        setter = annotation
    if kind == "point2d":
        setter = "Point"
    return getter, setter


def slot_validation(
    parameter: dict[str, Any], annotation: str, value: str
) -> list[str]:
    name = parameter["name"]
    kind = parameter["kind"]
    if kind == "point2d":
        return [
            f"if not isinstance({value}, Point):",
            f"    raise TypeError({name + ' must be Point'!r})",
            f"if not 0 <= {value}.x <= 1 or not 0 <= {value}.y <= 1:",
            f"    raise ValueError({name + ' must be within unit space'!r})",
        ]
    if kind == "active_interval" or kind == "enum" and " | str" not in annotation:
        target = "ActiveInterval" if kind == "active_interval" else annotation
        return [
            f"if not isinstance({value}, {target}):",
            f"    raise TypeError({name + ' must be ' + target!r})",
        ]
    return []


def slot_value(
    parameter: dict[str, Any], annotation: str, value: str, owner: str
) -> str:
    name, kind = parameter["name"], parameter["kind"]
    if kind in {"scalar_property", "plain_track"}:
        target = (
            "ModulatableScalarTrack" if kind == "scalar_property" else "ScalarTrack"
        )
        return f"{target}._create({owner}, {value})"
    if kind == "colour":
        return f"color_to_canonical({value})"
    if kind == "integer":
        return (
            f"_integer_in_range({value}, {name!r}, "
            f"{parameter['integer_minimum']}, {parameter['integer_maximum']})"
        )
    if kind == "number":
        return f"_number({value}, {name!r})"
    if kind == "point2d":
        return f"Point({value}.x, {value}.y)"
    if kind in {"active_interval", "enum"} and " | str" not in annotation:
        return value
    # Less common static fields use the same trust-boundary conversion as generic handles.
    expression = (
        f"_canonical_parameter(_parameter_descriptor(effect_definition("
        f"{'instance' if owner == 'owner' else 'self'}.kind), {name!r}), {value}, {owner}, "
        "validate_descriptor_values=False)"
    )
    if kind == "enum":
        return f"{annotation.removesuffix(' | str')}({expression})"
    getter, _ = property_types(parameter, annotation)
    return f"cast({getter}, {expression})"


def render_advanced_class(effect: dict[str, Any], effects: list[dict[str, Any]]) -> str:
    python = effect["python"]
    name, base = python["name"] + "Effect", advanced_base(effect)
    factory = python["collection"]["factory"]
    by_name = {parameter["name"]: parameter for parameter in effect["parameters"]}
    order = [arg.arg for arg in helper_arguments(effect).kwonlyargs if arg.arg != "id"]
    generic = base not in {"Effect", "_AmountEffect"}
    amount = factory == "amount"
    inherited = next(
        (item for item in effects if item["python"]["name"] == python["base"]), None
    )
    inherited_names = (
        {item["name"] for item in inherited["parameters"]} if inherited else set()
    )
    if base == "_AmountEffect":
        inherited_names.add("amount")
    fields = [field for field in order if field not in inherited_names]
    lines = [f"class {name}({base}):"]
    if not amount:
        slots = () if generic else tuple("_" + field for field in fields)
        lines.append(f"    __slots__ = {slots!r}")
        if generic:
            lines.append(f"    _effect_type = {effect['id']!r}")
        else:
            lines.extend(
                f"    _{field}: {advanced_types(by_name[field], python)[0]}"
                for field in fields
            )
        if not generic or base == "GenericEffect":
            method = (
                "_create_" + factory
                if factory in {"palette", "stylized"}
                else "_create"
            )
            lines += [
                "",
                "    @classmethod",
                f"    def {method}(",
                "        cls, owner: _Owner, scope: object, identifier: str,",
            ]
            if factory in {"palette", "stylized"}:
                lines.append("        parameters: Mapping[str, object],")
            else:
                lines.extend(
                    f"        {field}: {advanced_types(by_name[field], python)[1]},"
                    for field in order
                )
            lines.append("    ) -> Self:")
            if generic:
                supplied = (
                    "parameters"
                    if factory in {"palette", "stylized"}
                    else "{" + ", ".join(f"{field!r}: {field}" for field in order) + "}"
                )
                lines += [
                    "        definition = effect_definition(cls._effect_type)",
                    "        values = _build_registered_effect(",
                    "            cls._effect_type, owner, scope, identifier,",
                    f"            {supplied}, validate_descriptor_values=True,",
                    "        )",
                    "        values.pop('id')",
                    "        values.pop('type')",
                    "        return cast(Self, super()._create(owner, scope, identifier, definition, values))",
                ]
            else:
                for field in order:
                    _, annotation = advanced_types(by_name[field], python)
                    lines.extend(
                        "        " + line
                        for line in slot_validation(by_name[field], annotation, field)
                    )
                lines += [
                    "        instance = object.__new__(cls)",
                    f"        instance._initialize(owner, scope, identifier, {effect['id']!r})",
                ]
                for field in order:
                    _, annotation = advanced_types(by_name[field], python)
                    lines.append(
                        f"        instance._{field} = {slot_value(by_name[field], annotation, field, 'owner')}"
                    )
                lines.append("        return instance")
        for parameter in effect["parameters"]:
            field, kind = parameter["name"], parameter["kind"]
            if field in inherited_names:
                continue
            getter, setter = advanced_types(parameter, python)
            lines += ["", "    @property", f"    def {field}(self) -> {getter}:"]
            if not generic:
                expression = f"self._{field}"
            elif kind in {"scalar_property", "plain_track", "point_property"}:
                method = (
                    "parameter_point_track"
                    if kind == "point_property"
                    else "parameter_track"
                )
                expression = f"cast({getter}, self.{method}({field!r}))"
            elif kind == "enum":
                expression = f"{getter}(self._data[{field!r}])"
            elif kind == "palette":
                expression = f"tuple(cast(list[str], self._data[{field!r}]))"
            elif kind == "palette_stops":
                lines.append(f"        value = self._data.get({field!r})")
                expression = (
                    "None if value is None else tuple(cast(list[float], value))"
                )
            else:
                access = (
                    f"self._data.get({field!r})"
                    if kind in {"period", "font"} or python.get("get_values", False)
                    else f"self._data[{field!r}]"
                )
                expression = f"cast({getter}, {access})"
            lines.append(f"        return {expression}")
            if kind in {"scalar_property", "plain_track", "point_property"}:
                continue
            lines += [
                "",
                f"    @{field}.setter",
                f"    def {field}(self, value: {setter}) -> None:",
            ]
            if generic:
                lines.append(f"        self._set_parameter({field!r}, value)")
            else:
                lines.extend(
                    "        " + line
                    for line in slot_validation(parameter, setter, "value")
                )
                lines.append(
                    f"        self._{field} = {slot_value(parameter, setter, 'value', 'self._owner')}"
                )
    if not generic:
        direct = python.get("advanced_serialization") == "direct"
        if not amount or not direct:
            lines += ["", "    def to_canonical(self) -> dict[str, object]:"]
            if direct:
                lines.append("        return {**self._canonical(),")
                for field in order:
                    kind = by_name[field]["kind"]
                    expression = f"self.{field}"
                    if kind in {"scalar_property", "plain_track", "point2d"}:
                        expression += ".to_canonical()"
                    elif kind == "enum":
                        expression += ".value"
                    lines.append(f"            {field!r}: {expression},")
            else:
                lines.append("        return _canonical_typed_effect(self, {")
                lines.extend(f"            {field!r}: self.{field}," for field in order)
            lines.append("        }" + ("" if direct else ")"))
    if len(lines) == 1:
        lines.append("    pass")
    return "\n".join(lines) + "\n"


def render_advanced(effects: list[dict[str, Any]]) -> str:
    pending = [
        effect for effect in effects if effect["python"]["collection"] is not None
    ]
    defined = {"Effect", "GenericEffect", "_AmountEffect"}
    classes = []
    while pending:
        ready = next((item for item in pending if advanced_base(item) in defined), None)
        if ready is None:
            raise ValueError(
                "advanced effect bases contain an unknown class or inheritance cycle"
            )
        classes.append(render_advanced_class(ready, effects))
        defined.add(ready["python"]["name"] + "Effect")
        pending.remove(ready)
    return "\n\n".join(classes)


def replace_section(text: str, begin: str, end: str, body: str) -> str:
    if text.count(begin) != 1 or text.count(end) != 1:
        raise ValueError(
            f"expected one generated section delimited by {begin!r} / {end!r}"
        )
    before, rest = text.split(begin, 1)
    _, after = rest.split(end, 1)
    return before + begin + "\n" + body.rstrip() + "\n" + end + after


def section(text: str, begin: str, end: str) -> str:
    if text.count(begin) != 1 or text.count(end) != 1:
        raise ValueError(
            f"expected one generated section delimited by {begin!r} / {end!r}"
        )
    return text.split(begin, 1)[1].split(end, 1)[0]


def import_names(source: str) -> set[str]:
    return {
        alias.asname or alias.name
        for node in ast.parse(source).body
        if isinstance(node, ast.ImportFrom)
        for alias in node.names
    }


def public_exports(
    source: str, old_names: set[str], entries: list[tuple[str, int | None]]
) -> str:
    declaration = next(
        (
            node
            for node in ast.parse(source).body
            if isinstance(node, ast.Assign)
            and any(
                isinstance(target, ast.Name) and target.id == "__all__"
                for target in node.targets
            )
        ),
        None,
    )
    if declaration is None:
        return source
    exports = [
        name for name in ast.literal_eval(declaration.value) if name not in old_names
    ]
    positions = [position for _, position in entries if position is not None]
    if len(positions) != len(set(positions)):
        raise ValueError("Python effect exports contain duplicate historical positions")
    for name, position in sorted(
        entries, key=lambda entry: (entry[1] is None, entry[1] or 0)
    ):
        if name in exports:
            exports.remove(name)
        if position is None:
            exports.append(name)
        else:
            exports.insert(position, name)
    replacement = (
        "__all__ = [\n"
        + "".join(f"    {json.dumps(name)},\n" for name in exports)
        + "]\n"
    )
    lines = source.splitlines(keepends=True)
    return (
        "".join(lines[: declaration.lineno - 1])
        + replacement
        + "".join(lines[declaration.end_lineno :])
    )


def render_module_imports(source: str, effects: list[dict[str, Any]]) -> str:
    modules = {
        "typing": {"cast"},
        "collections.abc": {"Sequence"},
        "os": {"PathLike"},
        "..properties": {
            "ScalarProperty",
            "BindableScalarProperty",
            "BindablePointProperty",
        },
        "..authoring.values": {"Color", "Point"},
        "..authoring.effects": {"ActiveInterval", *enum_definitions(effects)},
        ".base": {"Effect"},
    }
    used = {
        node.id
        for node in ast.walk(ast.parse(source))
        if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load)
    }
    imports = [
        f"from {module} import {', '.join(sorted(names & used))}"
        for module, names in modules.items()
        if names & used
    ]
    return replace_section(source, IMPORT_BEGIN, IMPORT_END, "\n".join(imports))


def render_facade(source: str, metadata: dict[str, Any], scope: str) -> str:
    effects = metadata["effects"]
    old_names = import_names(section(source, IMPORT_BEGIN, IMPORT_END))
    groups: dict[str, list[str]] = {}
    entries: list[tuple[str, int | None]] = []
    for effect in effects:
        python = effect["python"]
        if scope == "authoring" and python["collection"] is None:
            continue
        name = python["name"] + ("Effect" if scope == "authoring" else "")
        module = (
            "." + python["module"].removeprefix("vestra.effects.")
            if scope == "effects"
            else ".effects"
        )
        groups.setdefault(module, []).append(name)
        entries.append((name, python.get("exports", {}).get(scope)))
    for name in enum_definitions(effects):
        layout = metadata.get("enum_exports", {}).get(name)
        if layout is not None and scope not in layout:
            continue
        module = "..authoring.effects" if scope == "effects" else ".effects"
        groups.setdefault(module, []).append(name)
        entries.append((name, None if layout is None else layout[scope]))
    imports = "\n".join(
        f"from {module} import (\n"
        + "".join(f"    {name},\n" for name in sorted(names))
        + ")"
        for module, names in sorted(groups.items())
    )
    source = public_exports(source, old_names, entries)
    return replace_section(source, IMPORT_BEGIN, IMPORT_END, imports)


class Stub(ast.NodeTransformer):
    def visit_ImportFrom(self, node: ast.ImportFrom) -> ast.ImportFrom:
        if node.module != "__future__":
            for alias in node.names:
                alias.asname = alias.asname or alias.name
        return node


def render_stub(source: str) -> str:
    tree = Stub().visit(ast.parse(source))

    def declaration(node: ast.AST, indent: str = "") -> str:
        if isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(base) for base in node.bases)
            body = "\n\n".join(declaration(item, indent + "    ") for item in node.body)
            return f"{indent}class {node.name}({bases}):\n{body}"
        if isinstance(node, ast.FunctionDef):
            decorators = "".join(
                f"{indent}@{ast.unparse(item)}\n" for item in node.decorator_list
            )
            returns = ast.unparse(node.returns)
            header = function_header(node.name, node.args, returns, indent)
            signature = ", ".join(
                line.strip().removesuffix(",") for line in header.splitlines()[1:-1]
            )
            short = f"{indent}def {node.name}({signature}) -> {returns}: ..."
            if len(short) <= 100:
                return decorators + short
            return decorators + header + f"\n{indent}    ..."
        return textwrap.indent(ast.unparse(node), indent)

    return f"# {NOTICE}\n" + "\n\n".join(declaration(node) for node in tree.body) + "\n"


def render_reference(effects: list[dict[str, Any]]) -> str:
    lines = [
        "# Effect parameter reference",
        "",
        f"<!-- {NOTICE} -->",
        "",
        "Python defaults below are authoring conveniences. The JSON column reports schema",
        "metadata; see [effects](effects.md) for parser behavior and legacy exceptions,",
        "including the required Ascii enum fields that the schema marks optional.",
        "Pass counts are catalog estimates; actual topology can depend on parameters.",
        "",
    ]
    for effect in effects:
        python = effect["python"]
        lines += [
            f"## {python['name']} (`{effect['id']}`)",
            "",
            f"Scope: `{effect['scope']}`; stage: `{effect['stage']}`; estimated passes: "
            f"{effect['estimated_pass_count']}; catalog retention: `{str(effect['retains_original']).lower()}`; "
            f"temporal policy: `{effect['temporal_policy']}`.",
            "",
            "| Parameter | Kind | Python default | JSON Schema requirement/default | Range | Units | Animation |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        authored = {arg.arg: default for arg, default in parameters(arguments(effect))}
        units = dict(effect["units"])
        for item in effect["parameters"]:
            name, kind = item["name"], item["kind"]
            default = authored[name]
            python_default = (
                "required" if default is None else f"`{ast.unparse(default)}`"
            )
            wire = "required" if item["required"] else "optional"
            if item["default"] is not None:
                wire += f"; `{json.dumps(item['default'])}`"
            minimum = (
                item.get("integer_minimum") if kind == "integer" else item["minimum"]
            )
            maximum = (
                item.get("integer_maximum") if kind == "integer" else item["maximum"]
            )
            bounds = (
                "finite"
                if kind in {"scalar_property", "plain_track", "number", "period"}
                else "—"
            )
            if minimum is not None or maximum is not None:

                def number(value: int | float) -> str:
                    return (
                        str(int(value))
                        if isinstance(value, float) and value.is_integer()
                        else str(value)
                    )

                if maximum is None:
                    bounds = ("> " if item["minimum_exclusive"] else ">= ") + number(
                        minimum
                    )
                elif minimum is None:
                    bounds = ("< " if item["maximum_exclusive"] else "<= ") + number(
                        maximum
                    )
                else:
                    bounds = (
                        ("(" if item["minimum_exclusive"] else "[")
                        + number(minimum)
                        + ", "
                        + number(maximum)
                        + (")" if item["maximum_exclusive"] else "]")
                    )
            if kind == "enum":
                bounds = ", ".join(f"`{value}`" for value in item["enum_values"])
            elif kind in {"palette", "palette_stops"}:
                bounds = "2..16 entries; see effect constraints"
            animation = {
                "scalar_property": "keyframes + signals",
                "plain_track": "keyframes",
                "point_property": "point keyframes + signals",
            }.get(kind, "static")
            cells = [
                f"`{name}`",
                f"`{kind}`",
                python_default,
                wire,
                bounds,
                units.get(name, "—"),
                animation,
            ]
            lines.append(
                "| " + " | ".join(cell.replace("|", r"\|") for cell in cells) + " |"
            )
        lines.append("")
    return "\n".join(lines)


def outputs(metadata: dict[str, Any], root: Path) -> dict[Path, str]:
    validate(metadata)
    effects = metadata["effects"]
    result: dict[Path, str] = {}
    modules = sorted({item["python"]["module"] for item in effects})
    for module in modules:
        path = Path("python/vestra/effects") / (
            module.removeprefix("vestra.effects.") + ".py"
        )
        items = [item for item in effects if item["python"]["module"] == module]
        classes = []
        amount = next(
            (item for item in items if item["python"]["base"] == "_AmountEffect"), None
        )
        if amount:
            classes.append(render_class(amount, effects, amount_base=True))
        classes.extend(render_class(item, effects) for item in items)
        body = f"# {NOTICE}\n\n" + "\n\n".join(classes)
        previous = (
            (root / path).read_text()
            if (root / path).exists()
            else (
                "from __future__ import annotations\n\n"
                + IMPORT_BEGIN
                + "\n"
                + IMPORT_END
                + "\n\n"
                + BEGIN
                + "\n"
                + END
                + "\n\n__all__ = []\n"
            )
        )
        old_names = {
            node.name
            for node in ast.parse(section(previous, BEGIN, END)).body
            if isinstance(node, ast.ClassDef) and not node.name.startswith("_")
        }
        source = replace_section(previous, BEGIN, END, body)
        source = render_module_imports(source, effects)
        source = public_exports(
            source,
            old_names,
            [
                (
                    item["python"]["name"],
                    item["python"].get("exports", {}).get("source"),
                )
                for item in items
                if item["python"].get("source_export", True)
            ],
        )
        result[path] = source
        result[path.with_suffix(".pyi")] = render_stub(source)
    authoring = Path("python/vestra/authoring/effects.py")
    source = (root / authoring).read_text()
    source = replace_section(source, ENUM_BEGIN, ENUM_END, render_enums(effects))
    source = replace_section(
        source, ADVANCED_BEGIN, ADVANCED_END, render_advanced(effects)
    )
    for scope, begin, end in [
        ("clip_and_global", HELPER_BEGIN, HELPER_END),
        ("clip_only", CLIP_BEGIN, CLIP_END),
    ]:
        helpers = [
            render_helper(item)
            for item in effects
            if item["scope"] == scope and item["python"]["collection"] is not None
        ]
        source = replace_section(source, begin, end, "\n".join(helpers) or "    pass")
    result[authoring] = source
    for scope, path in [
        ("root", "python/vestra/__init__.py"),
        ("effects", "python/vestra/effects/__init__.py"),
        ("authoring", "python/vestra/authoring/__init__.py"),
    ]:
        relative = Path(path)
        result[relative] = render_facade((root / relative).read_text(), metadata, scope)
    base = Path("python/vestra/effects/base.py")
    source = (root / base).read_text()
    enum_types = (
        "_ENUM_TYPES: Mapping[tuple[str, str], type[Enum]] = MappingProxyType({\n"
        + "".join(
            f"    ({effect['id']!r}, {parameter['name']!r}): {effect['python']['enums'][parameter['name']]},\n"
            for effect in effects
            for parameter in effect["parameters"]
            if parameter["kind"] == "enum"
        )
        + "})"
    )
    source = replace_section(source, ENUM_TYPES_BEGIN, ENUM_TYPES_END, enum_types)
    imports = (
        "from ..authoring.effects import (\n"
        + "".join(f"    {name},\n" for name in sorted(enum_definitions(effects)))
        + ")"
    )
    result[base] = replace_section(
        source, IMPORT_BEGIN, IMPORT_END, imports if enum_definitions(effects) else ""
    )
    result[Path("schemas/project.schema.json")] = metadata["schema"]
    result[Path("docs/reference/effect-parameters.md")] = render_reference(effects)
    return result


def synchronize(expected: dict[Path, str], root: Path, *, check: bool) -> list[Path]:
    stale = [
        path
        for path, content in expected.items()
        if not (root / path).exists() or (root / path).read_bytes() != content.encode()
    ]
    if not check:
        for path in stale:
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_bytes(expected[path].encode())
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="report stale artifacts without writing"
    )
    options = parser.parse_args()
    try:
        completed = subprocess.run(
            [
                "cargo",
                "run",
                "--locked",
                "--quiet",
                "-p",
                "vestra-core",
                "--example",
                "effect_metadata",
                "--",
                "schemas/project.schema.json",
            ],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
        python_metadata = runpy.run_path(
            str(ROOT / "scripts/effects/python_metadata.py")
        )
        metadata = with_python(
            json.loads(completed.stdout),
            python_metadata["PYTHON"],
            python_metadata["ENUM_EXPORTS"],
        )
        stale = synchronize(outputs(metadata, ROOT), ROOT, check=options.check)
    except subprocess.CalledProcessError as error:
        print(error.stderr, file=sys.stderr)
        return 1
    except (ValueError, KeyError, OSError, SyntaxError) as error:
        print(f"effect generation failed: {error}", file=sys.stderr)
        return 1
    if stale and options.check:
        print(
            "Stale effect artifacts; run just gen-effects:\n"
            + "\n".join(map(str, stale)),
            file=sys.stderr,
        )
        return 1
    print(
        f"Effect artifacts {'checked' if options.check else 'updated'} ({len(stale)} changed)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
