#!/usr/bin/env python3
"""Generate effect authoring declarations from the core catalog (stdlib only)."""

from __future__ import annotations

import argparse
import ast
import json
import runpy
from pathlib import Path
import subprocess
import sys
import textwrap
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "# BEGIN GENERATED EFFECTS"
END = "# END GENERATED EFFECTS"
HELPER_BEGIN = "    # BEGIN GENERATED EFFECT HELPERS"
HELPER_END = "    # END GENERATED EFFECT HELPERS"
CLIP_BEGIN = "    # BEGIN GENERATED CLIP EFFECT HELPERS"
CLIP_END = "    # END GENERATED CLIP EFFECT HELPERS"
NOTICE = "Generated by just gen-effects; edit the catalog or scripts/effects/python_metadata.py."
KINDS = {
    "scalar_property",
    "plain_track",
    "colour",
    "palette",
    "palette_stops",
    "period",
    "integer",
    "number",
    "point2d",
    "point_property",
    "boolean",
    "enum",
    "active_interval",
    "string",
    "font",
}


ANNOTATIONS = {
    "scalar_property": "int | float | ScalarProperty",
    "plain_track": "int | float | ScalarProperty",
    "colour": "Color | str",
    "palette": "Sequence[Color | str]",
    "palette_stops": "Sequence[int | float] | None",
    "period": "int | float | None",
    "integer": "int",
    "number": "int | float",
    "point2d": "Point | tuple[int | float, int | float]",
    "point_property": "Point | tuple[int | float, int | float]",
    "boolean": "bool",
    "active_interval": "ActiveInterval",
    "string": "str",
    "font": "str | PathLike[str] | None",
}


def with_python(metadata: dict[str, Any], overrides: dict[str, Any]) -> dict[str, Any]:
    ids = {effect["id"] for effect in metadata["effects"]}
    if ids != set(overrides):
        raise ValueError(
            f"Python overrides must cover the catalog: missing={sorted(ids - set(overrides))}, "
            f"unknown={sorted(set(overrides) - ids)}"
        )
    effects = []
    for effect in metadata["effects"]:
        python = dict(overrides[effect["id"]])
        python["name"] = "".join(word.title() for word in effect["id"].split("_"))
        python["module"] = "vestra.effects." + python["module"]
        python.setdefault("base", "Effect")
        python.setdefault("doc", None)
        factory = python.pop("helper")
        python["collection"] = (
            None
            if factory is None
            else {"factory": factory, "parameter_order": python.pop("helper_order", [])}
        )
        effects.append(
            {**effect, "python": python, "units": list(python.pop("units", {}).items())}
        )
    return {**metadata, "effects": effects}


def arguments(effect: dict[str, Any]) -> ast.arguments:
    python = effect["python"]
    fields = {item["name"]: item for item in effect["parameters"]}
    order = python.get("order", list(fields))
    if len(order) != len(fields) or set(order) != set(fields):
        raise ValueError(
            f"{effect['id']}: constructor order must cover every parameter once"
        )
    count = python.get("positional", len(order))
    if not isinstance(count, int) or not 0 <= count <= len(order):
        raise ValueError(f"{effect['id']}: invalid positional argument count")
    args, defaults = [], []
    for name in order:
        parameter = fields[name]
        kind = parameter["kind"]
        if kind not in KINDS:
            raise ValueError(f"{effect['id']}.{name}: unsupported kind {kind!r}")
        annotation = python.get("annotations", {}).get(name)
        enum = python.get("enums", {}).get(name)
        if annotation is None:
            if kind == "enum" and enum is None:
                raise ValueError(f"{effect['id']}.{name}: missing Python enum class")
            annotation = enum + " | str" if kind == "enum" else ANNOTATIONS[kind]
        value = python.get("defaults", {}).get(name, parameter["default"])
        if kind == "enum" and (
            enum is None
            or not enum.isidentifier()
            or value not in parameter["enum_values"]
        ):
            raise ValueError(f"{effect['id']}.{name}: invalid Python enum/default")
        expression = python.get("expressions", {}).get(name)
        if expression is not None:
            default = ast.parse(expression, mode="eval").body
        elif value is not None:
            expression = f"{enum}.{value.upper()}" if kind == "enum" else repr(value)
            default = ast.parse(expression, mode="eval").body
        elif not parameter["required"] or name in python.get("defaults", {}):
            default = ast.Constant(None)
        else:
            default = None
        args.append(
            ast.arg(arg=name, annotation=ast.parse(annotation, mode="eval").body)
        )
        defaults.append(default)
    positional_defaults = defaults[:count]
    first = next(
        (i for i, default in enumerate(positional_defaults) if default is not None),
        count,
    )
    if any(default is None for default in positional_defaults[first:]):
        raise ValueError(
            f"{effect['id']}: required positional argument follows a default"
        )
    return ast.arguments(
        posonlyargs=[],
        args=[ast.arg(arg="self"), *args[:count]],
        defaults=positional_defaults[first:],
        vararg=None,
        kwonlyargs=[
            *args[count:],
            ast.arg(arg="id", annotation=ast.parse("str | None", mode="eval").body),
        ],
        kw_defaults=[*defaults[count:], ast.Constant(None)],
        kwarg=None,
    )


def parameters(args: ast.arguments) -> list[tuple[ast.arg, ast.expr | None]]:
    defaults = [None] * (len(args.args) - len(args.defaults)) + args.defaults
    return list(zip(args.args + args.kwonlyargs, defaults + args.kw_defaults))


def validate(metadata: dict[str, Any]) -> None:
    ids: set[str] = set()
    names: set[str] = set()
    for effect in metadata["effects"]:
        identifier = effect["id"]
        python = effect["python"]
        if not isinstance(python, dict):
            raise ValueError(f"{identifier}: missing Python authoring metadata")
        if identifier in ids or python["name"] in names:
            raise ValueError(f"{identifier}: duplicate effect id or Python name")
        ids.add(identifier)
        names.add(python["name"])
        if (
            not python["module"].startswith("vestra.effects.")
            or not python["module"].removeprefix("vestra.effects.").isidentifier()
            or not python["name"].isidentifier()
        ):
            raise ValueError(f"{identifier}: invalid Python module or class name")
        expected = [item["name"] for item in effect["parameters"]]
        if len(expected) != len(set(expected)):
            raise ValueError(f"{identifier}: duplicate parameter name")
        for key in ("enums", "annotations", "defaults", "expressions"):
            if set(python.get(key, {})) - set(expected):
                raise ValueError(f"{identifier}: {key} reference an unknown parameter")
        if set(python.get("defaults", {})) & set(python.get("expressions", {})):
            raise ValueError(f"{identifier}: duplicate default override")
        args = arguments(effect)
        authored = parameters(args)
        actual = [arg.arg for arg, _ in authored if arg.arg not in {"self", "id"}]
        if any(arg.annotation is None for arg, _ in authored if arg.arg != "self"):
            raise ValueError(
                f"{identifier}: every public argument needs a type annotation"
            )
        for item in effect["parameters"]:
            if item["kind"] not in KINDS:
                raise ValueError(
                    f"{identifier}.{item['name']}: unsupported kind {item['kind']!r}"
                )
            for prefix in ("", "integer_"):
                minimum, maximum = (
                    item.get(prefix + "minimum"),
                    item.get(prefix + "maximum"),
                )
                if minimum is not None and maximum is not None and minimum > maximum:
                    raise ValueError(f"{identifier}.{item['name']}: inverted bounds")
            if item["kind"] == "enum" and (
                not item["enum_values"] or item["default"] not in item["enum_values"]
            ):
                raise ValueError(f"{identifier}.{item['name']}: invalid enum/default")
        if set(dict(effect["units"])) - set(expected):
            raise ValueError(f"{identifier}: units reference an unknown parameter")
        collection = python["collection"]
        if collection is not None:
            if collection["factory"] not in {
                "positional",
                "amount",
                "palette",
                "stylized",
            }:
                raise ValueError(f"{identifier}: unsupported collection factory")
            order = collection["parameter_order"] or actual
            if len(order) != len(actual) or set(order) != set(actual):
                raise ValueError(
                    f"{identifier}: helper order must cover every parameter once"
                )
    for effect in metadata["effects"]:
        base = effect["python"]["base"]
        if base not in names | {"Effect", "_AmountEffect"}:
            raise ValueError(f"{effect['id']}: unsupported base {base!r}")
    if not isinstance(metadata["schema"], str) or not metadata["schema"].endswith("\n"):
        raise ValueError("core export must include the canonical schema text")
    schema = json.loads(metadata["schema"])
    branches = {
        item["$ref"].removeprefix("#/$defs/").removesuffix("_effect")
        for item in schema["$defs"]["effect"]["oneOf"]
    }
    if branches != ids:
        raise ValueError("schema effect branches do not match the catalog")


def function_header(
    name: str, args: ast.arguments, returns: str, indent: str = "    "
) -> str:
    lines = [f"{indent}def {name}("]
    positional = len(args.args)
    for index, (arg, default) in enumerate(parameters(args)):
        if index == positional and args.kwonlyargs:
            lines.append(f"{indent}    *,")
        annotation = f": {ast.unparse(arg.annotation)}" if arg.annotation else ""
        value = f" = {ast.unparse(default)}" if default is not None else ""
        lines.append(f"{indent}    {arg.arg}{annotation}{value},")
    lines.append(f"{indent}) -> {returns}:")
    return "\n".join(lines)


def property_types(parameter: dict[str, Any], annotation: str) -> tuple[str, str]:
    kind = parameter["kind"]
    getter = {
        "scalar_property": "BindableScalarProperty",
        "plain_track": "ScalarProperty",
        "colour": "str",
        "palette": "tuple[str, ...]",
        "palette_stops": "tuple[float, ...] | None",
        "period": "float | None",
        "integer": "int",
        "number": "float",
        "point2d": "Point",
        "point_property": "BindablePointProperty",
        "boolean": "bool",
        "active_interval": "ActiveInterval",
        "string": "str",
        "font": annotation,
        "enum": annotation.removesuffix(" | str"),
    }[kind]
    setter = getter + " | str" if kind == "enum" else annotation
    return getter, setter


def render_class(
    effect: dict[str, Any], effects: list[dict[str, Any]], *, amount_base: bool = False
) -> str:
    python = effect["python"]
    name = "_AmountEffect" if amount_base else python["name"]
    base = "Effect" if amount_base else python["base"]
    lines = [f"class {name}({base}):"]
    if python["doc"] and not amount_base:
        doc = python["doc"].replace('"""', '\\"\\"\\"')
        lines.append(textwrap.indent('"""' + doc + '"""', "    "))
    if base == "_AmountEffect":
        lines.append(f"    effect_type = {effect['id']!r}")
        return "\n".join(lines) + "\n"
    lines.append("    __slots__ = ()")
    if not amount_base:
        lines.append(f"    effect_type = {effect['id']!r}")
    args = arguments(effect)
    fields = {
        arg.arg: ast.unparse(arg.annotation)
        for arg, _ in parameters(args)
        if arg.arg not in {"self", "id"}
    }
    lines += ["", function_header("__init__", args, "None")]
    lines.append(
        "        Effect.__init__(self)"
        if base != "Effect"
        else "        super().__init__()"
    )
    lines += ["        self._init(", "            {"]
    lines.extend(f"                {field!r}: {field}," for field in fields)
    lines += ["            },", "            id=id,", "        )"]
    inherited = next((item for item in effects if item["python"]["name"] == base), None)
    inherited_names = (
        {item["name"] for item in inherited["parameters"]} if inherited else set()
    )
    for parameter in effect["parameters"]:
        field = parameter["name"]
        if field in inherited_names:
            continue
        getter, setter = property_types(parameter, fields[field])
        kind = parameter["kind"]
        storage = (
            "_properties"
            if kind in {"scalar_property", "plain_track", "point_property"}
            else "_values"
        )
        access = (
            f"self.{storage}.get({field!r})"
            if kind in {"font", "period", "palette_stops"}
            or (storage == "_values" and python.get("get_values", False))
            else f"self.{storage}[{field!r}]"
        )
        method = (
            "_set_property"
            if kind in {"scalar_property", "plain_track"}
            else "_set_value"
        )
        lines += [
            "",
            "    @property",
            f"    def {field}(self) -> {getter}:",
            f"        return cast({getter}, {access})",
            "",
            f"    @{field}.setter",
            f"    def {field}(self, value: {setter}) -> None:",
            f"        self.{method}({field!r}, value)",
        ]
    return "\n".join(lines) + "\n"


def helper_arguments(effect: dict[str, Any]) -> ast.arguments:
    collection = effect["python"]["collection"]
    authored = parameters(arguments(effect))
    values = {arg.arg: (arg, default) for arg, default in authored if arg.arg != "self"}
    order = collection["parameter_order"] or [name for name in values if name != "id"]
    kinds = {item["name"]: item["kind"] for item in effect["parameters"]}
    kwargs, defaults = [], []
    for name in [*order, "id"]:
        arg, default = values[name]
        annotation = ast.unparse(arg.annotation)
        annotation = (
            annotation.replace("ScalarProperty", "ScalarTrack")
            if collection["factory"] in {"palette", "stylized"}
            else annotation.replace(" | ScalarProperty", "")
        )
        if kinds.get(name) in {"point2d", "point_property"}:
            annotation = "Point"
        elif kinds.get(name) == "font":
            annotation = "FontAsset | None"
        if default is not None and ast.unparse(default) == "CHARACTER_SETS['standard']":
            default = ast.Constant(" .:-=+*#%@")
        kwargs.append(
            ast.arg(arg=name, annotation=ast.parse(annotation, mode="eval").body)
        )
        defaults.append(default)
    return ast.arguments(
        posonlyargs=[],
        args=[ast.arg(arg="self")],
        vararg=None,
        kwonlyargs=kwargs,
        kw_defaults=defaults,
        kwarg=None,
        defaults=[],
    )


def render_helper(effect: dict[str, Any]) -> str:
    args = helper_arguments(effect)
    name = effect["python"]["name"] + "Effect"
    factory = effect["python"]["collection"]["factory"]
    fields = [arg.arg for arg in args.kwonlyargs if arg.arg != "id"]
    if factory in {"palette", "stylized"}:
        method = "_create_palette" if factory == "palette" else "_create_stylized"
        values = [
            "            {",
            *[f"                {field!r}: {field}," for field in fields],
            "            },",
        ]
    else:
        method = "_create"
        values = [
            f"            {value},"
            for value in ([repr(effect["id"])] if factory == "amount" else []) + fields
        ]
    return (
        function_header("add_" + effect["id"], args, name) + "\n"
        f"        return self._append(\n            {name}.{method},\n            id,\n"
        + "\n".join(values)
        + "\n        )\n"
    )


def replace_section(text: str, begin: str, end: str, body: str) -> str:
    if text.count(begin) != 1 or text.count(end) != 1:
        raise ValueError(
            f"expected one generated section delimited by {begin!r} / {end!r}"
        )
    before, rest = text.split(begin, 1)
    _, after = rest.split(end, 1)
    return before + begin + "\n" + body.rstrip() + "\n" + end + after


class Stub(ast.NodeTransformer):
    def visit_ImportFrom(self, node: ast.ImportFrom) -> ast.ImportFrom:
        if node.module != "__future__":
            for alias in node.names:
                alias.asname = alias.asname or alias.name
        return node


def render_stub(source: str) -> str:
    tree = Stub().visit(ast.parse(source))

    def declaration(node: ast.AST, indent: str = "") -> str:
        if isinstance(node, ast.ClassDef):
            bases = ", ".join(ast.unparse(base) for base in node.bases)
            body = "\n\n".join(declaration(item, indent + "    ") for item in node.body)
            return f"{indent}class {node.name}({bases}):\n{body}"
        if isinstance(node, ast.FunctionDef):
            decorators = "".join(
                f"{indent}@{ast.unparse(item)}\n" for item in node.decorator_list
            )
            returns = ast.unparse(node.returns)
            header = function_header(node.name, node.args, returns, indent)
            signature = ", ".join(
                line.strip().removesuffix(",") for line in header.splitlines()[1:-1]
            )
            short = f"{indent}def {node.name}({signature}) -> {returns}: ..."
            if len(short) <= 100:
                return decorators + short
            return decorators + header + f"\n{indent}    ..."
        return textwrap.indent(ast.unparse(node), indent)

    return f"# {NOTICE}\n" + "\n\n".join(declaration(node) for node in tree.body) + "\n"


def render_reference(effects: list[dict[str, Any]]) -> str:
    lines = [
        "# Effect parameter reference",
        "",
        f"<!-- {NOTICE} -->",
        "",
        "Python defaults below are authoring conveniences. The JSON column reports schema",
        "metadata; see [effects](effects.md) for parser behavior and legacy exceptions,",
        "including the required Ascii enum fields that the schema marks optional.",
        "Pass counts are catalog estimates; actual topology can depend on parameters.",
        "",
    ]
    for effect in effects:
        python = effect["python"]
        lines += [
            f"## {python['name']} (`{effect['id']}`)",
            "",
            f"Scope: `{effect['scope']}`; stage: `{effect['stage']}`; estimated passes: "
            f"{effect['estimated_pass_count']}; catalog retention: `{str(effect['retains_original']).lower()}`; "
            f"temporal policy: `{effect['temporal_policy']}`.",
            "",
            "| Parameter | Kind | Python default | JSON Schema requirement/default | Range | Units | Animation |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        authored = {arg.arg: default for arg, default in parameters(arguments(effect))}
        units = dict(effect["units"])
        for item in effect["parameters"]:
            name, kind = item["name"], item["kind"]
            default = authored[name]
            python_default = (
                "required" if default is None else f"`{ast.unparse(default)}`"
            )
            wire = "required" if item["required"] else "optional"
            if item["default"] is not None:
                wire += f"; `{json.dumps(item['default'])}`"
            minimum = (
                item.get("integer_minimum") if kind == "integer" else item["minimum"]
            )
            maximum = (
                item.get("integer_maximum") if kind == "integer" else item["maximum"]
            )
            bounds = (
                "finite"
                if kind in {"scalar_property", "plain_track", "number", "period"}
                else "—"
            )
            if minimum is not None or maximum is not None:

                def number(value: int | float) -> str:
                    return (
                        str(int(value))
                        if isinstance(value, float) and value.is_integer()
                        else str(value)
                    )

                if maximum is None:
                    bounds = ("> " if item["minimum_exclusive"] else ">= ") + number(
                        minimum
                    )
                elif minimum is None:
                    bounds = ("< " if item["maximum_exclusive"] else "<= ") + number(
                        maximum
                    )
                else:
                    bounds = (
                        ("(" if item["minimum_exclusive"] else "[")
                        + number(minimum)
                        + ", "
                        + number(maximum)
                        + (")" if item["maximum_exclusive"] else "]")
                    )
            if kind == "enum":
                bounds = ", ".join(f"`{value}`" for value in item["enum_values"])
            elif kind in {"palette", "palette_stops"}:
                bounds = "2..16 entries; see effect constraints"
            animation = {
                "scalar_property": "keyframes + signals",
                "plain_track": "keyframes",
                "point_property": "point keyframes + signals",
            }.get(kind, "static")
            cells = [
                f"`{name}`",
                f"`{kind}`",
                python_default,
                wire,
                bounds,
                units.get(name, "—"),
                animation,
            ]
            lines.append(
                "| " + " | ".join(cell.replace("|", r"\|") for cell in cells) + " |"
            )
        lines.append("")
    return "\n".join(lines)


def outputs(metadata: dict[str, Any], root: Path) -> dict[Path, str]:
    validate(metadata)
    effects = metadata["effects"]
    result: dict[Path, str] = {}
    modules = sorted({item["python"]["module"] for item in effects})
    for module in modules:
        path = Path("python/vestra/effects") / (
            module.removeprefix("vestra.effects.") + ".py"
        )
        items = [item for item in effects if item["python"]["module"] == module]
        classes = []
        amount = next(
            (item for item in items if item["python"]["base"] == "_AmountEffect"), None
        )
        if amount:
            classes.append(render_class(amount, effects, amount_base=True))
        classes.extend(render_class(item, effects) for item in items)
        body = f"# {NOTICE}\n\n" + "\n\n".join(classes)
        source = replace_section((root / path).read_text(), BEGIN, END, body)
        result[path] = source
        result[path.with_suffix(".pyi")] = render_stub(source)
    authoring = Path("python/vestra/authoring/effects.py")
    source = (root / authoring).read_text()
    for scope, begin, end in [
        ("clip_and_global", HELPER_BEGIN, HELPER_END),
        ("clip_only", CLIP_BEGIN, CLIP_END),
    ]:
        helpers = [
            render_helper(item)
            for item in effects
            if item["scope"] == scope and item["python"]["collection"] is not None
        ]
        source = replace_section(source, begin, end, "\n".join(helpers))
    result[authoring] = source
    result[Path("schemas/project.schema.json")] = metadata["schema"]
    result[Path("docs/reference/effect-parameters.md")] = render_reference(effects)
    return result


def synchronize(expected: dict[Path, str], root: Path, *, check: bool) -> list[Path]:
    stale = [
        path
        for path, content in expected.items()
        if not (root / path).exists() or (root / path).read_bytes() != content.encode()
    ]
    if not check:
        for path in stale:
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_bytes(expected[path].encode())
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="report stale artifacts without writing"
    )
    options = parser.parse_args()
    try:
        completed = subprocess.run(
            [
                "cargo",
                "run",
                "--locked",
                "--quiet",
                "-p",
                "vestra-core",
                "--example",
                "effect_metadata",
                "--",
                "schemas/project.schema.json",
            ],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        )
        overrides = runpy.run_path(str(ROOT / "scripts/effects/python_metadata.py"))[
            "PYTHON"
        ]
        metadata = with_python(json.loads(completed.stdout), overrides)
        stale = synchronize(outputs(metadata, ROOT), ROOT, check=options.check)
    except subprocess.CalledProcessError as error:
        print(error.stderr, file=sys.stderr)
        return 1
    except (ValueError, KeyError, OSError, SyntaxError) as error:
        print(f"effect generation failed: {error}", file=sys.stderr)
        return 1
    if stale and options.check:
        print(
            "Stale effect artifacts; run just gen-effects:\n"
            + "\n".join(map(str, stale)),
            file=sys.stderr,
        )
        return 1
    print(
        f"Effect artifacts {'checked' if options.check else 'updated'} ({len(stale)} changed)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
